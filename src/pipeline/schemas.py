"""PyArrow schema definitions for all 15 curated output tables.

Every schema includes metadata columns: league_id, season, dt, run_id, _loaded_at.
Column names and types match the existing dbt staging models exactly.
"""

from __future__ import annotations

import pyarrow as pa


def _meta_fields() -> list[pa.Field]:
    return [
        pa.field("league_id", pa.int32()),
        pa.field("season", pa.int32()),
        pa.field("dt", pa.string()),
        pa.field("run_id", pa.string()),
        pa.field("_loaded_at", pa.string()),
    ]


