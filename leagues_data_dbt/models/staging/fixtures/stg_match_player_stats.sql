with source_dedup as (
    select
        raw,
        league_id,
        season,
        dt,
        run_id,
        _loaded_at
    from {{ source('raw', 'raw_fixtures_players') }}
    qualify row_number() over (
        partition by league_id, season, raw:entity_key::varchar
        order by _loaded_at desc
    ) = 1
),
team_nodes as (
    select
        source_dedup.raw:params:fixture::int as fixture_id,
        team.value:team:id::int as team_id,
        team.value:team:name::varchar as team_name,
        team.value:team:logo::varchar as team_logo,
        team.value:players as players,
        source_dedup.league_id,
        source_dedup.season,
        source_dedup.dt,
        source_dedup.run_id,
        source_dedup._loaded_at
    from source_dedup,
        lateral flatten(input => source_dedup.raw:payload:response) team
),
flattened as (
    select
        fixture_id,
        team_id,
        team_name,
        team_logo,
        p.value:player:id::int as player_id,
        p.value:player:name::varchar as player_name,
        p.value:player:photo::varchar as player_photo,
        p.value:statistics[0]:games:number::int as shirt_number,
        p.value:statistics[0]:games:position::varchar as position,
        p.value:statistics[0]:games:rating::float as rating,
        p.value:statistics[0]:games:minutes::int as minutes_played,
        p.value:statistics[0]:games:captain::boolean as is_captain,
        p.value:statistics[0]:games:substitute::boolean as is_substitute,
        p.value:statistics[0]:offsides::int as offsides,
        p.value:statistics[0]:shots:total::int as shots_total,
        p.value:statistics[0]:shots:on::int as shots_on_target,
        p.value:statistics[0]:goals:total::int as goals_total,
        p.value:statistics[0]:goals:conceded::int as goals_conceded,
        p.value:statistics[0]:goals:assists::int as assists,
        p.value:statistics[0]:goals:saves::int as saves,
        p.value:statistics[0]:passes:total::int as passes_total,
        p.value:statistics[0]:passes:key::int as key_passes,
        p.value:statistics[0]:passes:accuracy::int as passes_accuracy,
        p.value:statistics[0]:tackles:total::int as tackles_total,
        p.value:statistics[0]:tackles:blocks::int as blocks,
        p.value:statistics[0]:tackles:interceptions::int as interceptions,
        p.value:statistics[0]:duels:total::int as duels_total,
        p.value:statistics[0]:duels:won::int as duels_won,
        p.value:statistics[0]:dribbles:attempts::int as dribbles_attempted,
        p.value:statistics[0]:dribbles:success::int as dribbles_success,
        p.value:statistics[0]:dribbles:past::int as dribbled_past,
        p.value:statistics[0]:fouls:drawn::int as fouls_drawn,
        p.value:statistics[0]:fouls:committed::int as fouls_committed,
        p.value:statistics[0]:cards:yellow::int as yellow_cards,
        p.value:statistics[0]:cards:red::int as red_cards,
        p.value:statistics[0]:penalty:won::int as penalties_won,
        p.value:statistics[0]:penalty:commited::int as penalties_committed,
        p.value:statistics[0]:penalty:scored::int as penalties_scored,
        p.value:statistics[0]:penalty:missed::int as penalties_missed,
        p.value:statistics[0]:penalty:saved::int as penalties_saved,
        league_id,
        season,
        dt,
        run_id,
        _loaded_at
    from team_nodes,
        lateral flatten(input => team_nodes.players) p
),
deduped as (
    select
        fixture_id,
        team_id,
        team_name,
        team_logo,
        player_id,
        player_name,
        player_photo,
        shirt_number,
        position,
        rating,
        minutes_played,
        is_captain,
        is_substitute,
        offsides,
        shots_total,
        shots_on_target,
        goals_total,
        goals_conceded,
        assists,
        saves,
        passes_total,
        key_passes,
        passes_accuracy,
        tackles_total,
        blocks,
        interceptions,
        duels_total,
        duels_won,
        dribbles_attempted,
        dribbles_success,
        dribbled_past,
        fouls_drawn,
        fouls_committed,
        yellow_cards,
        red_cards,
        penalties_won,
        penalties_committed,
        penalties_scored,
        penalties_missed,
        penalties_saved,
        league_id,
        season,
        dt,
        run_id,
        _loaded_at
    from flattened
    qualify row_number() over (
        partition by league_id, season, fixture_id, team_id, player_id
        order by coalesce(minutes_played, -1) desc, coalesce(rating, -1) desc, _loaded_at desc
    ) = 1
)

